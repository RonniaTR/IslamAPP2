// Küresel ayet numarası ofsetleri (cdn.islamic.network URL'leri için)
// OFFSETS[i] = i indeksli sureden ÖNCEKİ toplam ayet sayısı
export const SURAH_OFFSETS = SURAHS.reduce((acc, s, i) => {
  acc.push(i === 0 ? 0 : acc[i - 1] + SURAHS[i - 1].ayahs);
  return acc;
}, []);

/** Küresel ayet numarası (1-6236) → ses URL'si */
export function verseAudioUrl(surahNo, ayahNo, reciterId = 'ar.alafasy', quality = 128) {
  const global = SURAH_OFFSETS[surahNo - 1] + ayahNo;
  return `https://cdn.islamic.network/quran/audio/${quality}/${reciterId}/${global}.mp3`;
}

