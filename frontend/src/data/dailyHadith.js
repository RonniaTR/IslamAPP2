// Günün hadisini tarih bazlı seç (her gün farklı)
export function getDailyHadith() {
  const today = new Date();
  const dayOfYear = Math.floor((today - new Date(today.getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24));
  return DAILY_HADITHS[dayOfYear % DAILY_HADITHS.length];
}

// Kategori bazlı filtreleme
export function getHadithsByCategory(category) {
  return DAILY_HADITHS.filter(h => h.category === category);
}
